"""The Projects and Feedback-owners block, rendered from the tasks resolver.

Every project with a records entry is listed, whichever projects this host holds, so the
block is the same on every host. A project whose resolved profile is private leaves the
global block; a session under that profile lists it instead (`private_listing`).
"""
import pathlib

from ._configuration import ProfileError
from ._tasks import query

START = ('<!-- ops:projects start — generated by lore from tasks resolve; change the project\'s'
         ' identity.toml (then tasks identity refresh) or its tasks records entry -->')
END = '<!-- ops:projects end -->'
HEADER = """## Projects

Backticked names below are project prefixes: when one appears in a request it means
that project, not an ordinary word. `tasks projects` prints their paths and status,
and `list`, `ready`, `next`, `prime`, `tree`, `tags`, and `sample` each take `--project <prefix>`
to read one of them from anywhere.
"""
FEEDBACK_HEADER = """
### Feedback owners

The projects that accept feedback, and what each owns. File with
`tasks feedback --project <prefix> "<one line>" --category <friction|gap|idea|positive>`;
the Feedback section above says when.
"""


def catalogue(env):
    """Every records entry the resolver lists, keyed and sorted by prefix."""
    rows = {}
    for row in query(['resolve', '--all', '--json'], env)['results']:
        prefix, entry = row.get('prefix'), row.get('entry')
        if not isinstance(prefix, str) or not isinstance(entry, dict):
            raise ProfileError(f"tasks resolve --all: row {row.get('input')!r} lacks a prefix or records entry")
        if prefix in rows:
            raise ProfileError(f'tasks resolve --all: {prefix} is listed twice')
        rows[prefix] = row
    return dict(sorted(rows.items()))


def profile_names(row, config, env):
    """The profiles a records entry resolves to without any per-clone override: the
    assignment, else lore's path rules for its checkout, else the default."""
    from ._profiles import _selection
    return _selection(pathlib.Path(row['entry']['checkout']), row, config, env, override=False)[0]


def private_profiles(config):
    return {name for name, table in config['profile'].items() if table.get('private') is True}


def _identity(prefix, entry):
    """(name, aliases, purpose), or None when the entry has no identity snapshot yet. A
    missing snapshot renders as a placeholder rather than refusing, so `just assemble` in
    lore always succeeds and the block shows its own gap where a reader will see it."""
    if 'name' not in entry and 'purpose' not in entry:
        return None
    for key in ('name', 'purpose'):
        if not isinstance(entry.get(key), str) or not entry[key]:
            raise ProfileError(f'{prefix}: records entry has an invalid identity {key}')
    aliases = entry.get('aliases', [])
    if not isinstance(aliases, list) or any(not isinstance(a, str) for a in aliases):
        raise ProfileError(f'{prefix}: records entry has invalid aliases')
    return entry['name'], aliases, entry['purpose']


def _placeholder(prefix):
    return (f'(no identity recorded — run `tasks identity refresh {prefix}`, or seed it with'
            f' `tasks identity refresh {prefix} --from <file>`)')


def retirement(prefix, entry):
    """The entry's retirement table, None when it has none."""
    value = entry.get('retired')
    if value is None:
        return None
    if (not isinstance(value, dict) or not isinstance(value.get('date'), str)
            or not isinstance(value.get('successor', ''), str)):
        raise ProfileError(f'{prefix}: invalid retirement metadata')
    return value


def project_line(prefix, entry):
    identity = _identity(prefix, entry)
    if identity is None:
        return f'- `{prefix}` — {_placeholder(prefix)}'
    name, aliases, purpose = identity
    named = name + (f" ({', '.join(aliases)})" if aliases else '')
    return f'- `{prefix}` — {named} — {purpose}'


def retired_line(entries):
    """The one line naming retired projects, so an old id read in a note still says what
    it was; None when there are none. `entries` maps prefix to records entry."""
    clauses = []
    for prefix, entry in entries.items():
        retired = retirement(prefix, entry)
        arrow = f" → `{retired['successor']}`" if retired.get('successor') else ''
        identity = _identity(prefix, entry)
        name = identity[0] if identity else 'no identity recorded'
        clauses.append(f"`{prefix}` ({name}, {retired['date']}){arrow}")
    return 'Retired: ' + '; '.join(clauses) + '.' if clauses else None


def listing(entries):
    """Project lines for live entries, then the retired line, in prefix order."""
    live = {p: e for p, e in entries.items() if retirement(p, e) is None}
    lines = [project_line(p, e) for p, e in live.items()]
    line = retired_line({p: e for p, e in entries.items() if p not in live})
    return lines, line


def render(entries):
    """The whole marked block as bytes, ending in one newline. `entries` maps each listed
    prefix (private ones already removed) to its records entry."""
    entries = dict(sorted(entries.items()))
    lines, retired = listing(entries)
    owners = []
    for prefix, entry in entries.items():
        scope = entry.get('feedback')
        if scope is None or retirement(prefix, entry) is not None:
            continue
        if not isinstance(scope, str) or not scope or '\n' in scope:
            raise ProfileError(f'{prefix}: invalid feedback scope')
        owners.append(f'- `{prefix}` — {scope}')
    tail = ['', retired] if retired else []
    feedback = [FEEDBACK_HEADER, *owners] if owners else []
    return ('\n'.join([START, HEADER, *lines, *tail, *feedback, END]) + '\n').encode()


def global_block(env):
    """The global block for this host's resolver and lore's profile definitions."""
    from ._profiles import _config
    config = _config(env)
    private = private_profiles(config)
    rows = catalogue(env)
    return render({p: r['entry'] for p, r in rows.items() if not private & set(profile_names(r, config, env))})


def private_listing(names, config, env):
    """The lines a session under the private profiles among `names` adds: the projects
    those profiles hold, then their retired line."""
    selected = private_profiles(config) & set(names)
    if not selected:
        return []
    rows = catalogue(env)
    lines, retired = listing({p: r['entry'] for p, r in rows.items()
                              if selected & set(profile_names(r, config, env))})
    return lines + ([retired] if retired else [])
