"""The checker validates staged or working instructions from the repository root."""
import os
import subprocess
import sys
from pathlib import Path

import pytest

HOOK = Path(__file__).with_name("check-projects-block")
START = "<!-- ops:projects start — generated by ops-projects; edit identity.toml in the project, or identity-mirror.toml in ops -->"
PREVIOUS = "<!-- ops:projects start — generated by ops-projects; edit identity-mirror.toml in ops -->"
END = "<!-- ops:projects end -->"
BLOCK = f"{START}\n## Projects\n\n- `ai` — agent config\n{END}"


def sh(cwd, *args, **kw):
    return subprocess.run(args, cwd=cwd, check=True, text=True, capture_output=True, **kw).stdout


@pytest.fixture
def world(tmp_path):
    """A fake ops checkout whose ops-projects renders BLOCK, a registry naming it, and an ai repo."""
    ops = tmp_path / "ops"
    (ops / "bin").mkdir(parents=True)
    stub = ops / "bin" / "ops-projects"
    stub.write_text("#!/usr/bin/env python3\nimport sys\nassert sys.argv[1] == 'render'\n"
                    f"print({BLOCK!r})\n")
    stub.chmod(0o755)
    config = tmp_path / "config" / "tasks"
    config.mkdir(parents=True)
    (config / "projects.toml").write_text(f'[projects]\nops = "{ops}"\nai = "{tmp_path / "ai"}"\n')
    repo = tmp_path / "ai"
    repo.mkdir()
    sh(repo, "git", "init", "-q")
    sh(repo, "git", "config", "user.email", "t@example.com")
    sh(repo, "git", "config", "user.name", "t")
    (repo / "instructions").mkdir()
    (repo / "instructions/AGENTS.md").write_text(f"# rules\n\n{BLOCK}\n")
    sh(repo, "git", "add", "instructions/AGENTS.md")
    sh(repo, "git", "commit", "-q", "-m", "init")
    env = {**os.environ, "XDG_CONFIG_HOME": str(tmp_path / "config")}
    return repo, env, tmp_path


def run_hook(repo, env):
    return subprocess.run([sys.executable, str(HOOK)], cwd=repo, env=env, text=True, capture_output=True)


def test_passes_when_staged_block_matches_render(world):
    repo, env, _ = world
    (repo / "instructions/AGENTS.md").write_text(f"# rules, edited\n\n{BLOCK}\n")
    sh(repo, "git", "add", "instructions/AGENTS.md")
    r = run_hook(repo, env)
    assert r.returncode == 0, r.stderr


def test_accepts_the_previous_marker_while_ops_still_renders_it(world):
    repo, env, tmp = world
    old = BLOCK.replace(START, PREVIOUS)
    stub = tmp / "ops" / "bin" / "ops-projects"
    stub.write_text("#!/usr/bin/env python3\nimport sys\nassert sys.argv[1] == 'render'\n"
                    f"print({old!r})\n")
    (repo / "instructions/AGENTS.md").write_text(f"# rules, edited\n\n{BLOCK}\n")
    sh(repo, "git", "add", "instructions/AGENTS.md")
    assert run_hook(repo, env).returncode == 0


def test_marker_bridge_replaces_only_the_start_marker(world):
    repo, env, tmp = world
    old = BLOCK.replace(START, PREVIOUS)
    old = old.replace(END, f"{PREVIOUS}\n{END}")
    current = old.replace(PREVIOUS, START, 1)
    stub = tmp / "ops" / "bin" / "ops-projects"
    stub.write_text("#!/usr/bin/env python3\nimport sys\nassert sys.argv[1] == 'render'\n"
                    f"print({old!r})\n")
    (repo / "instructions/AGENTS.md").write_text(f"# rules, edited\n\n{current}\n")
    sh(repo, "git", "add", "instructions/AGENTS.md")
    assert run_hook(repo, env).returncode == 0


def test_refuses_a_hand_edited_block(world):
    repo, env, _ = world
    edited = BLOCK.replace("- `ai` — agent config", "- `ai` — agent config\n- `zz` — hand-written")
    (repo / "instructions/AGENTS.md").write_text(f"# rules\n\n{edited}\n")
    sh(repo, "git", "add", "instructions/AGENTS.md")
    r = run_hook(repo, env)
    assert r.returncode == 1
    assert "identity-mirror.toml" in r.stderr and "+- `zz`" in r.stderr
    assert "differs from ops-projects render" in r.stderr


def test_judges_the_staged_content_not_the_worktree(world):
    repo, env, _ = world
    (repo / "instructions/AGENTS.md").write_text(f"# rules, staged edit\n\n{BLOCK}\n")
    sh(repo, "git", "add", "instructions/AGENTS.md")
    (repo / "instructions/AGENTS.md").write_text("# rules\n\nblock removed on disk only\n")
    assert run_hook(repo, env).returncode == 0


def test_checks_disk_when_agents_md_is_not_staged(world):
    repo, env, _ = world
    (repo / "other.txt").write_text("x\n")
    sh(repo, "git", "add", "other.txt")
    (repo / "instructions/AGENTS.md").write_text("# drifted on disk but unstaged\n")
    result = run_hook(repo, env)
    assert result.returncode == 1 and "markers" in result.stderr


def test_refuses_a_staged_agents_md_without_markers(world):
    repo, env, _ = world
    (repo / "instructions/AGENTS.md").write_text("# rules\n\nno block\n")
    sh(repo, "git", "add", "instructions/AGENTS.md")
    r = run_hook(repo, env)
    assert r.returncode == 1 and "markers" in r.stderr


def test_fails_loudly_when_ops_is_unregistered(world):
    repo, env, tmp = world
    (tmp / "config" / "tasks" / "projects.toml").write_text(f'[projects]\nai = "{repo}"\n')
    (repo / "instructions/AGENTS.md").write_text(f"# rules, edited\n\n{BLOCK}\n")
    sh(repo, "git", "add", "instructions/AGENTS.md")
    r = run_hook(repo, env)
    assert r.returncode == 1 and "ops" in r.stderr and "registered" in r.stderr


def test_fails_loudly_when_registry_is_missing(world):
    repo, env, tmp = world
    (tmp / "config" / "tasks" / "projects.toml").unlink()
    (repo / "instructions/AGENTS.md").write_text(f"# rules, edited\n\n{BLOCK}\n")
    sh(repo, "git", "add", "instructions/AGENTS.md")
    r = run_hook(repo, env)
    assert r.returncode == 1 and "projects.toml" in r.stderr


def test_refuses_a_staged_deletion_cleanly(world):
    repo, env, _ = world
    sh(repo, "git", "rm", "-q", "instructions/AGENTS.md")
    r = run_hook(repo, env)
    assert r.returncode == 1 and "deletion" in r.stderr and "Traceback" not in r.stderr


def test_fails_loudly_when_ops_projects_is_missing(world):
    repo, env, tmp = world
    (tmp / "ops" / "bin" / "ops-projects").unlink()
    (repo / "instructions/AGENTS.md").write_text(f"# rules, edited\n\n{BLOCK}\n")
    sh(repo, "git", "add", "instructions/AGENTS.md")
    r = run_hook(repo, env)
