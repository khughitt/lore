def test_fails_loudly_when_render_fails(world):
    repo, env, tmp = world
    stub = tmp / "ops" / "bin" / "ops-projects"
    stub.write_text("#!/usr/bin/env python3\nimport sys\nsys.stderr.write('ops-projects: bad identity-mirror.toml\\n')\nsys.exit(1)\n")
    (repo / "instructions/AGENTS.md").write_text(f"# rules, edited\n\n{BLOCK}\n")
    sh(repo, "git", "add", "instructions/AGENTS.md")
    r = run_hook(repo, env)
    assert r.returncode == 1 and "render failed" in r.stderr and "bad identity-mirror.toml" in r.stderr


def test_bad_staged_block_cannot_be_hidden_by_restoring_disk(world):
    repo, env, _ = world
    file = repo / "instructions/AGENTS.md"
    good = file.read_text()
    file.write_text("# invalid staged instructions\n")
    sh(repo, "git", "add", "instructions/AGENTS.md")
    file.write_text(good)
    result = run_hook(repo, env)
    assert result.returncode == 1
    assert "markers" in result.stderr


def test_refuses_a_staged_rename_cleanly(world):
    repo, env, _ = world
    sh(repo, "git", "mv", "instructions/AGENTS.md", "instructions/renamed.md")
    result = run_hook(repo, env)
    assert result.returncode == 1
    assert "rename" in result.stderr and "Traceback" not in result.stderr
